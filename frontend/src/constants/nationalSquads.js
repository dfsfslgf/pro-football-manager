function makeStatBlock(pos, ovr) {
  if (pos === 'GK') {
    return {
      speed: Math.max(55, ovr - 14),
      shooting: 45,
      passing: Math.max(65, ovr - 10),
      dribbling: Math.max(60, ovr - 14),
      defense: Math.max(70, ovr - 6),
      physical: Math.max(74, ovr - 4),
      gkReflexes: ovr + 2,
    };
  }
  if (pos === 'DF') {
    return {
      speed: ovr - 2,
      shooting: ovr - 16,
      passing: ovr - 4,
      dribbling: ovr - 5,
      defense: ovr + 3,
      physical: ovr + 2,
      gkReflexes: 40,
    };
  }
  if (pos === 'MF') {
    return {
      speed: ovr - 1,
      shooting: ovr - 2,
      passing: ovr + 3,
      dribbling: ovr + 2,
      defense: ovr - 4,
      physical: ovr - 2,
      gkReflexes: 40,
    };
  }
  return {
    speed: ovr + 2,
    shooting: ovr + 3,
    passing: ovr - 3,
    dribbling: ovr + 2,
    defense: ovr - 18,
    physical: ovr - 1,
    gkReflexes: 40,
  };
}

/**
 * 선택한 국가 코드(48개국 전체 지원)에 맞춰 2026 월드컵 26인 최종 엔트리를 생성함
 */
export function buildNationalSquad(nationObjOrCode) {
  const rawKey = typeof nationObjOrCode === 'string' ? nationObjOrCode : nationObjOrCode?.code || nationObjOrCode?.name || 'KOR';
  const entry =
    WC_2026_NATIONAL_ROSTERS[rawKey] ||
    Object.values(WC_2026_NATIONAL_ROSTERS).find((r) => r.name === rawKey) ||
    WC_2026_NATIONAL_ROSTERS.KOR;

  const builtPlayers = entry.players.map((p, idx) => {
    const baseStats = makeStatBlock(p.pos, p.ovr);
    const uid = -(100 + idx);
    return {
      id: `HOME-${uid}`,
      side: 'HOME',
      userPlayerId: uid,
      playerId: uid,
      name: p.name,
      mainPosition: p.pos,
      preferredRoleCode: p.role,
      secondaryRoleCode: null,
      roleCodes: [p.role],
      level: 1,
      maxLevel: 20,
      suspendedMatches: 0,
      exp: 0,
      stamina: 100,
      currentStamina: 100,
      baseStats,
      effectiveStats: computeEffectiveStats(baseStats, 1),
      tags: p.ovr >= 85 ? ['LEGEND'] : ['EPIC'],
      rarity: p.ovr >= 85 ? 'LEGEND' : 'EPIC',
      overall: p.ovr,
      instruction: null,
      backNumber: p.no || idx + 1,
    };
  });

  return {
    formation: entry.formation || '4-2-3-1',
    starters: builtPlayers.slice(0, 11),
    bench: builtPlayers.slice(11, 22),
    reserve: builtPlayers.slice(22, 26),
  };
}