function findRosterForTeam(teamName) {
  const clean = String(teamName || '').trim();
  for (const [natName, roster] of Object.entries(NATIONAL_TEAM_SQUADS)) {
    if (clean.includes(natName) || natName.includes(clean)) return roster;
  }
  for (const [clubKey, roster] of Object.entries(CLUB_TEAM_SQUADS)) {
    if (clean.includes(clubKey) || clubKey.includes(clean)) return roster;
  }
  return null;
}

function makeStats(rng, mainPosition, targetStrength) {
  const posKey = resolveMainPosition(mainPosition);
  const w = ROLE_WEIGHTS[posKey] || ROLE_WEIGHTS.MF;
  const stats = {};
  for (const key of STAT_KEYS) {
    const raw = targetStrength * (w[key] || 1) + rng.int(-4, 4);
    stats[key] = Math.max(40, Math.min(97, Math.round(raw)));
  }
  return stats;
}

function makeAiPlayer(rng, id, rawMainPosition, rawRoleCode, strength, namePool, usedNames) {
  const mainPosition = resolveMainPosition(rawMainPosition, rawRoleCode);
  const roleCode = String(rawRoleCode || mainPosition).toUpperCase().trim();
  const baseStats = makeStats(rng, mainPosition, strength);

  const primaryList = Array.isArray(namePool?.[mainPosition]) ? namePool[mainPosition] : INTERNATIONAL_POOL[mainPosition];
  const fallbackList = Array.isArray(INTERNATIONAL_POOL[mainPosition]) ? INTERNATIONAL_POOL[mainPosition] : INTERNATIONAL_POOL.MF;

  const candidates = primaryList.filter((n) => !usedNames.has(n));
  const fallbackCandidates = fallbackList.filter((n) => !usedNames.has(n));

  const pickedName =
    candidates.length > 0
      ? rng.pick(candidates)
      : fallbackCandidates.length > 0
      ? rng.pick(fallbackCandidates)
      : rng.pick(primaryList.length > 0 ? primaryList : fallbackList);

  usedNames.add(pickedName);

  return {
    userPlayerId: -id,
    playerId: -id,
    name: pickedName,
    mainPosition,
    preferredRoleCode: roleCode,
    secondaryRoleCode: null,
    roleCodes: [roleCode],
    level: 1,
    stamina: 100,
    baseStats,
    overall: computeOverall(baseStats, 1, mainPosition),
    rarity: strength >= 84 ? 'LEGEND' : strength >= 76 ? 'EPIC' : 'RARE',
    instruction: null,
  };
}

export function buildOpponent({ seed, name, strength = 75, formation = null, tactics = null }) {
  const rng = createRng(seed || `${name}-${strength}`);
  const formCodes = Object.keys(FORMATIONS);
  const chosenFormation = formation && FORMATIONS[formation] ? formation : rng.pick(formCodes);
  const slots = getFormationSlots(chosenFormation);

  const matchedRoster = findRosterForTeam(name);
  const activePool = matchedRoster || INTERNATIONAL_POOL;
  const usedNames = new Set();

  let seq = 1;
  const starters = slots.map((slot) => {
    const slotRoleCode = slot.roleCode || slot.role || slot.code || 'CM';
    const slotGroup = resolveMainPosition(slot.roleGroup || slot.mainPosition || slot.group, slotRoleCode);
    return makeAiPlayer(rng, seq++, slotGroup, slotRoleCode, strength + rng.int(-2, 2), activePool, usedNames);
  });

  const benchRoles = [
    ['GK', 'GK'],
    ['DF', 'CB'],
    ['DF', 'LB'],
    ['DF', 'RB'],
    ['MF', 'CDM'],
    ['MF', 'CM'],
    ['MF', 'CAM'],
    ['FW', 'LW'],
    ['FW', 'RW'],
    ['FW', 'ST'],
    ['FW', 'ST'],
  ];
  const bench = benchRoles.map(([pos, role]) =>
    makeAiPlayer(rng, seq++, pos, role, strength - 2, activePool, usedNames)
  );

  const defaultTactics = {
    mentality: rng.pick(['DEFENSIVE', 'BALANCED', 'ATTACKING']),
    passingStyle: rng.pick(['SHORT', 'MIXED', 'DIRECT_LONG']),
    tempo: rng.pick(['SLOW', 'NORMAL', 'FAST']),
    defensiveLine: rng.pick(['DEEP', 'NORMAL', 'HIGH']),
    pressing: rng.pick(['LOW', 'MEDIUM', 'HIGH']),
    offsideTrap: rng.pick(['OFF', 'ON']),
  };

  return {
    name,
    emblem: rng.pick(EMBLEMS),
    strength,
    formation: chosenFormation,
    tactics: { ...defaultTactics, ...(tactics || {}) },
    starters,
    bench,
  };
}

