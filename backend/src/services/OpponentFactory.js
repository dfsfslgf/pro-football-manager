function resolveMainPosition(rawGroup, rawRoleCode) {
  const g = String(rawGroup || '').toUpperCase().trim();
  if (g === 'GK' || g === 'DF' || g === 'MF' || g === 'FW') return g;

  const r = String(rawRoleCode || g || '').toUpperCase().trim();
  if (r === 'GK') return 'GK';
  if (DF_ROLES.has(r)) return 'DF';
  if (MF_ROLES.has(r)) return 'MF';
  if (FW_ROLES.has(r)) return 'FW';
  return 'MF';
}

